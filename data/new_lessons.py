def _ch(q, correct, wrong, pos, explain):
    """choice: правильный вариант ставится на позицию pos, остальные — по порядку."""
    opts = list(wrong)
    opts.insert(pos, correct)
    return {"type": "choice", "q": q, "options": opts, "answer": pos, "explain": explain}


def _ti(q, answer, explain, accept=None):
    d = {"type": "type_in", "q": q, "answer": answer, "explain": explain}
    if accept:
        d["accept"] = accept
    return d


def _order(q, answer, words, explain):
    return {"type": "order", "q": q, "words": words, "answer": answer, "explain": explain}


def _match(q, left, right, explain):
    return {"type": "match", "q": q, "left": left, "right": right,
            "pairs": {i: i for i in range(len(left))}, "explain": explain}


def _letters(spec):
    """spec: [(буква, имя, слово-пример)] → карточки алфавита."""
    return [{"en": l, "ru": f"буква {l} ({w})", "hint": h, "letter": True} for l, h, w in spec]


